#!/usr/bin/env node
// Build the scoped "SUNEXT dark futuristic" stylesheet from the standalone
// HTML template.
//
//   node scripts/build-sx-theme.mjs <template.html> <out.css>
//
// The template ships ~6k lines of layered, override-heavy CSS. Re-typing it
// as Tailwind would never be pixel-identical, so we copy it verbatim and
// scope it instead:
//
//   - every custom property `--x` is renamed `--sx-x` so it cannot shadow the
//     app's Tailwind/shadcn tokens (`--border`, `--card`, `--radius`, ...)
//   - every @keyframes name is prefixed `sx-` (globals.css reuses some names)
//   - `:root` / `html` / `body` map onto the `.sx-root` wrapper element
//   - shell selectors (sidebar, topbar, ...) are prefixed `.sx-root ` so the
//     chrome looks identical on every dashboard page
//   - everything else (KPI cards, panels, tables, modal, toasts) is prefixed
//     `.sx-root.sx-ov ` so it only applies on the overview page and cannot
//     leak into the legacy page bodies rendered inside the same shell.

import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const [, , srcArg, outArg] = process.argv;
if (!srcArg || !outArg) {
  console.error("usage: node scripts/build-sx-theme.mjs <template.html> <out.css>");
  process.exit(1);
}

const html = fs.readFileSync(path.resolve(srcArg), "utf8");
const match = html.match(/<style>([\s\S]*?)<\/style>/);
if (!match) {
  console.error("No <style> block found in template");
  process.exit(1);
}

const ROOT = ".sx-root";
const OV = ".sx-root.sx-ov";

// Classes that belong to the persistent chrome (sidebar + topbar). Anything
// referencing one of these is scoped to every page, not only the overview.
const SHELL_RE =
  /\.(app|sidebar(?:-[\w-]+)?|brand(?:-[\w-]+)?|nav-[\w-]+|online|main|topbar(?:-[\w-]+)?|mobile-menu-button|search-box|filter-control|period-filter|team-filter|project-filter|notification-[\w-]+|profile(?:-[\w-]+)?|icon-button|toast(?:-[\w-]+)?)(?![\w-])/;
const ROOT_RE = /^(:root|html|body)(?![\w-])/;
const BASE_ELEMENT_RE = /^(button|input|select|textarea|a|table)(?![\w-])/;

function scopeSelector(raw) {
  const sel = raw.trim();
  if (sel.includes(".sx-root")) return [sel];
  if (ROOT_RE.test(sel)) return [sel.replace(ROOT_RE, ROOT)];
  if (sel === "*") return [`${ROOT} *`];
  if (sel.startsWith("::")) return [`${ROOT} ${sel}`];
  if (BASE_ELEMENT_RE.test(sel)) {
    return [`${OV} ${sel}`, `${ROOT} .sidebar ${sel}`, `${ROOT} .topbar ${sel}`];
  }
  if (SHELL_RE.test(sel)) return [`${ROOT} ${sel}`];
  return [`${OV} ${sel}`];
}

const root = postcss.parse(match[1]);

// 1. Keyframes: collect + rename.
const keyframeNames = new Set();
root.walkAtRules(/keyframes$/i, (at) => {
  keyframeNames.add(at.params.trim());
  at.params = `sx-${at.params.trim()}`;
});
const keyframeRe = keyframeNames.size
  ? new RegExp(
      `(?<![\\w-])(${[...keyframeNames]
        .sort((a, b) => b.length - a.length)
        .map((n) => n.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
        .join("|")})(?![\\w-])`,
      "g",
    )
  : null;

// 2. Declarations: custom properties + animation references.
root.walkDecls((decl) => {
  if (decl.prop.startsWith("--")) decl.prop = `--sx-${decl.prop.slice(2)}`;
  decl.value = decl.value.replace(/var\(\s*--([\w-]+)/g, "var(--sx-$1");
  if (keyframeRe && /^(animation|animation-name)$/i.test(decl.prop)) {
    decl.value = decl.value.replace(keyframeRe, "sx-$1");
  }
});

// 3. Selectors (skip keyframe steps like `0%`, `from`, `to`).
root.walkRules((rule) => {
  const parent = rule.parent;
  if (parent && parent.type === "atrule" && /keyframes$/i.test(parent.name)) return;
  const next = [];
  for (const sel of rule.selectors) {
    for (const scoped of scopeSelector(sel)) {
      if (!next.includes(scoped)) next.push(scoped);
    }
  }
  rule.selectors = next;
});

const header = `/* AUTO-GENERATED by scripts/build-sx-theme.mjs — do not edit by hand.
 * Source: ${path.basename(srcArg)}
 * Scoped SUNEXT dark-futuristic template styles (see script header). */
`;
fs.writeFileSync(path.resolve(outArg), header + root.toString().trim() + "\n");
console.log(
  `wrote ${outArg} (${keyframeNames.size} keyframes renamed, ${root.nodes.length} top-level nodes)`,
);
