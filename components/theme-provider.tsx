"use client";

import { ThemeProvider as NextThemesProvider } from "next-themes";
import type { ReactNode } from "react";

export function ThemeProvider({ children }: { children: ReactNode }) {
  return (
    // The dashboard (V2 template) owns its light/dark mode via
    // `<html data-theme>`; keep next-themes from adding `.dark`, which would
    // apply legacy globals.css dark rules underneath it.
    <NextThemesProvider
      attribute="class"
      defaultTheme="light"
      forcedTheme="light"
      enableSystem={false}
      disableTransitionOnChange
    >
      {children}
    </NextThemesProvider>
  );
}
